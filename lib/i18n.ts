const dictionaries: Record<Lang, Record<Key, string>> = { en, es };

// Look up a word in the right language and fill in {blanks}
export function translate(
  lang: Lang,
  key: Key,
  vars?: Record<string, string | number>
): string {
  let text = dictionaries[lang]?.[key] ?? en[key] ?? String(key);
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.split(`{${k}}`).join(String(v));
    }
  }
  return text;
}

// A service name in the person's language (falls back to English)
export function jobName(
  n: { name: string; name_es: string | null } | null | undefined,
  lang: Lang
): string {
  if (!n) return "—";
  return lang === "es" && n.name_es ? n.name_es : n.name;
}

// Dates always print as MM/DD/YYYY so the whole crew reads them the same way
export function formatDate(iso: string | null | undefined): string {
  if (!iso) return "—";
  const [y, m, d] = iso.slice(0, 10).split("-");
  return `${m}/${d}/${y}`;
}

export function formatNumber(n: number | null | undefined): string {
  if (n === null || n === undefined) return "—";
  return Number(n).toLocaleString("en-US");
}

// "4,510 hrs" / "82,300 mi" / "" for machines without a meter
export function formatReading(
  n: number | null | undefined,
  meterType: "hours" | "miles" | "none",
  lang: Lang
): string {
  if (meterType === "none" || n === null || n === undefined) return "";
  const unit = translate(lang, meterType === "miles" ? "unit_mi" : "unit_hrs");
  return `${formatNumber(n)} ${unit}`;
}
